import math

# просим ввести x, сразу переводим в дробное число
x = float(input("Введите x (|x| < 1): "))
# просим ввести точность
eps = float(input("Введите точность eps (например, 0.0001): "))

# проверяем, что x не выходит за пределы (по формуле |x| < 1)
if abs(x) >= 1:
    print("Ошибка: |x| должно быть меньше 1")
# проверяем, что точность больше нуля (иначе цикл будет бесконечным)
elif eps <= 0:
    print("Ошибка: точность eps должна быть больше нуля!")
else:
    # тут будет копиться наша сумма
    s = 0.0
    # счетчик шагов
    n = 0
    # самое первое слагаемое это просто x (так как n=0)
    term = x

    # крутимся в цикле, пока текущее слагаемое по модулю больше точности
    while abs(term) >= eps:
        # добавляем слагаемое к общей сумме
        s += term

        # считаем коэффициент k для получения следующего слагаемого
        # (это рекуррентная формула: x^2 * (2n+1)/(2n+3))
        k = (x * x) * (2 * n + 1) / (2 * n + 3)

        # новое слагаемое = старое слагаемое умножить на k
        term = term * k

        # увеличиваем счетчик n для следующего шага
        n += 1

    # по формуле перед скобкой стоит двойка, поэтому умножаем сумму на 2
    result = 2 * s

    # считаем точное значение через встроенный логарифм для проверки
    exact = math.log((1 + x) / (1 - x))

    # выводим что получилось (6 знаков после запятой)
    print(f"Вычисленное значение: {result:.6f}")
    # выводим точный ответ (для сравнения)
    print(f"Точное значение (math): {exact:.6f}")
    # выводим сколько слагаемых успели сложить
    print(f"Количество учтенных членов: {n}")