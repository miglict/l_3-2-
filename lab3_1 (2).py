x_start = float(input("Xнач = "))
x_end = float(input("Xкон = "))
dx = float(input("dx = "))

print("-" * 40)
print(f"{'x':>10} | {'y':>10}")
print("-" * 40)

x = x_start
while x <= x_end + 1e-9:
    # 1. Левая наклонная прямая (от -4 до -2)
    if x < -2:
        y = 1.5 * x + 4

    # 2. Средняя наклонная прямая (от -2 до 4)
    elif x < 4:
        y = -0.5 * x

    # 3. Горизонтальная прямая (от 4 до 6)
    elif x < 6:
        y = -2

    # 4. Полуокружность (от 6 до 10)
    else:
        # проверяем, чтобы под корнем не было минуса
        if 4 - (x - 8) ** 2 >= 0:
            y = -2 + (4 - (x - 8) ** 2) ** 0.5
        else:
            y = "нет"  # если вдруг вылезли за радиус

    # Вывод
    if y == "нет":
        print(f"{x:10.2f} | {'Нет Y':>10}")
    else:
        print(f"{x:10.2f} | {y:10.3f}")

    x += dx